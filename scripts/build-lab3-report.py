def table(title, headers, rows, widths):
    global table_num
    table_num += 1
    p = para(f'Таблиця {table_num} – {title}', align=WD_ALIGN_PARAGRAPH.CENTER, keep=True, indent=False)
    p.paragraph_format.space_before = Pt(6)
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    borders = OxmlElement('w:tblBorders')
    for edge in ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']:
        b = OxmlElement(f'w:{edge}')
        b.set(qn('w:val'), 'single')
        b.set(qn('w:sz'), '4')
        b.set(qn('w:color'), '000000')
        borders.append(b)
    t._tbl.tblPr.append(borders)
    for col, width in zip(t.columns, widths):
        col.width = Cm(width)
    for values, row in [(headers, t.rows[0])] + [(values, t.add_row()) for values in rows]:
        no_split = OxmlElement('w:cantSplit')
        row._tr.get_or_add_trPr().append(no_split)
        for idx, (cell, value, width) in enumerate(zip(row.cells, values, widths)):
            cell.width = Cm(width)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_before = Pt(3)
            p.paragraph_format.space_after = Pt(3)
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if idx == 0 else WD_ALIGN_PARAGRAPH.LEFT
            r = p.add_run(str(value))
            r.bold = row == t.rows[0]
    repeat = OxmlElement('w:tblHeader')
    t.rows[0]._tr.get_or_add_trPr().append(repeat)
    return t


def figure(file, explanation, caption, max_height=17):
    global figure_num
    figure_num += 1
    para(explanation, keep=True)
    img = Image.open(S / file)
    width = min(17, max_height * img.width / img.height)
    p = para(align=WD_ALIGN_PARAGRAPH.CENTER, keep=True, indent=False)
    p.paragraph_format.line_spacing = 1
    p.add_run().add_picture(str(S / file), width=Cm(width))
    p = para(f'Рисунок {figure_num} – {caption}', align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)
    p.paragraph_format.space_after = Pt(6)


