def link(label, url):
    from docx.opc.constants import RELATIONSHIP_TYPE
    p = para(indent=False)
    r_id = p.part.relate_to(url, RELATIONSHIP_TYPE.HYPERLINK, is_external=True)
    h = OxmlElement('w:hyperlink')
    h.set(qn('r:id'), r_id)
    r = OxmlElement('w:r')
    props = OxmlElement('w:rPr')
    color = OxmlElement('w:color'); color.set(qn('w:val'), '000000'); props.append(color)
    r.append(props)
    text = OxmlElement('w:t'); text.text = label + ': ' + url; r.append(text)
    h.append(r); p._p.append(h)


