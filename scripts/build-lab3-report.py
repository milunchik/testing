def para(text='', *, align=None, bold=False, keep=False, indent=True):
    p = doc.add_paragraph()
    p.add_run(text).bold = bold
    p.paragraph_format.keep_with_next = keep
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        p.alignment = align
    return p


